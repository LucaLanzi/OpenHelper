import { join } from "node:path";
import { stringify as toYaml } from "yaml";
import { ws } from "./core/paths.js";
import type { ModelPack, Platform } from "./core/schemas.js";

export function modelsDir(): string {
  return process.env.OPENHELPER_MODELS ?? join(ws.root(), "models");
}

export function modelFile(m: ModelPack): string {
  return join(modelsDir(), m.source.filename || `${m.id}.gguf`);
}

/**
 * llama-swap config: every chat model in one exclusive group (one loaded at a time),
 * the embedding model in its own persistent group so search keeps working across swaps.
 * llama-server always binds to 127.0.0.1.
 */
export function llamaSwapConfig(platform: Platform, models: ModelPack[], llamaServer: string): string {
  const offered = models.filter((m) => !platform.model.allowed.length || platform.model.allowed.includes(m.id) || m.id === platform.model.current || m.id === platform.model.embed || m.id === platform.model.light);
  const entries: Record<string, unknown> = {};
  for (const m of offered) {
    const o = platform.model_overrides[m.id];
    const args = [
      llamaServer,
      "--host 127.0.0.1",
      "--port ${PORT}",
      `-m ${JSON.stringify(modelFile(m))}`,
      `-c ${o?.ctx ?? m.ctx_default}`,
      "-ngl 999",
      ...(o?.n_cpu_moe !== undefined ? [`--n-cpu-moe ${o.n_cpu_moe}`] : []),
      ...m.server_args,
      ...(o?.extra_args ?? []),
    ];
    entries[m.id] = {
      cmd: args.join(" "),
      ttl: platform.resources.unload_after_min * 60,
      ...(m.roles.includes("embed") ? {} : { aliases: [] }),
    };
  }
  const chat = offered.filter((m) => !m.roles.includes("embed")).map((m) => m.id);
  const embed = offered.filter((m) => m.roles.includes("embed")).map((m) => m.id);
  const doc = {
    healthCheckTimeout: 600,
    logLevel: "info",
    models: entries,
    groups: {
      chat: { swap: true, exclusive: true, members: chat },
      ...(embed.length ? { embed: { swap: false, exclusive: false, persistent: true, members: embed } } : {}),
    },
  };
  return `# Generated by \`openhelper llama-swap-config\`. Edit platform files, not this.\n${toYaml(doc)}`;
}
